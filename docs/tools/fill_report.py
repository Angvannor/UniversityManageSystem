def split_paragraphs(text):
    """按 <w:p> 切分，返回 [(start, end, body), ...]"""
    res = []
    i = 0
    while True:
        m = re.search(r"<w:p(?:\s[^>]*)?>", text[i:])
        if not m:
            break
        start = i + m.end()
        depth = 1
        j = start
        while depth > 0:
            nxt = re.search(r"<w:p(?:\s[^>]*)?>|</w:p>", text[j:])
            if not nxt:
                break
            if nxt.group(0).startswith("</"):
                depth -= 1
            else:
                depth += 1
            j += nxt.end()
        body = text[start:j - len("</w:p>")] if depth == 0 else text[start:j]
        res.append((i + m.start(), j, body))
        i = j
    return res


def para_text(body):
    """取出段落纯文字"""
    return "".join(html.unescape(x) for x in re.findall(r"<w:t[^>]*>(.*?)</w:t>", body, re.S))


def xml_escape(s):
    """XML 转义（中文原样保留）"""
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_text_inner(text):
    """
    生成要插入「已有 <w:t> 节点内容位置」的文本。
    多行时先闭合当前节点，用 <w:br/> 换行后再开一个新节点，
    因此这里不带首尾的 <w:t> 标签。
    """
    parts = [xml_escape(p) for p in text.split("\n")]
    return '</w:t><w:br/><w:t xml:space="preserve">'.join(parts)


def build_text_element(text):
    """
    生成完整的 <w:t> 片段（用于空单元格插入新 run 的场景）。
    """
    parts = [xml_escape(p) for p in text.split("\n")]
    return ('<w:t xml:space="preserve">'
            + '</w:t><w:br/><w:t xml:space="preserve">'.join(parts)
            + '</w:t>')


def replace_paragraph_text(body, text):
    """
    替换段落内的文字。

    :param body: 段落内容（不含 <w:p> 开标签与 </w:p> 闭标签）
    :param text: 新文字，\n 表示单元格内换行
    :return: 新的段落内容
    """
    matches = list(re.finditer(r"(<w:t[^>]*>)(.*?)(</w:t>)", body, re.S))

    if matches:
        # 1) 先把「除第一个之外」的文本节点清空（保留原有 run / 格式结构）。
        #    必须从后往前删，否则前面的位置会失效。
        for m in reversed(matches[1:]):
            body = body[:m.start(2)] + body[m.end(2):]
        # 2) 再把第一个节点的内容替换成我们的文字。
        #    此时只改动了第一个节点之后的位置，first 的位置仍然有效。
        first = matches[0]
        body = body[:first.start(2)] + build_text_inner(text) + body[first.end(2):]
        return body

    # 空单元格：段落里没有任何 <w:t>，插入一个新的 run
    return body + '<w:r>' + FONT + build_text_element(text) + '</w:r>'


def count_paragraphs(xml):
    return len(re.findall(r"<w:p(?:\s[^>]*)?>", xml))


def apply_stack_fixes(xml):
    """
    先应用「技术栈改写」：把报告里原本写的 Vue/Spring Boot/MyBatis 表述
    改成与实际代码一致的「纯 Java 控制台程序 + JDBC + MySQL」。

    这部分逻辑复用 report_stack_fix.py，避免两处维护同一份替换清单。
    """
    import importlib.util
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "report_stack_fix.py")
    spec = importlib.util.spec_from_file_location("report_stack_fix", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)

    count = 0
    for old, new, _reason in sorted(mod.REPLACEMENTS, key=lambda x: len(x[0]), reverse=True):
        xml, done = mod.replace_in_text_node(xml, old, new)
        if done:
            count += 1
    print("技术栈改写：应用 %d 处" % count)
    return xml


def main():
    # 1. 从备份恢复，保证可重复执行
    if not os.path.exists(BAK):
        shutil.copy2(DOCX, BAK)
        print("已创建备份:", os.path.basename(BAK))
    else:
        shutil.copy2(BAK, DOCX)
        print("已从备份恢复原始报告")

    zin = zipfile.ZipFile(DOCX, "r")
    items = zin.infolist()
    blobs = {i.filename: zin.read(i.filename) for i in items}
    zin.close()

    xml = blobs["word/document.xml"].decode("utf-8")

    # 1.5 先做技术栈改写（4.1 总体设计、4.2 业务流程、2.2 需求措辞）
    xml = apply_stack_fixes(xml)

    before = count_paragraphs(xml)

    # 2. 逐条填写（先自检占位符是否匹配，再替换）
    ok, fail = 0, []
    for idx, expect, content, desc in FILLS:
        paras = split_paragraphs(xml)
        if idx >= len(paras):
            fail.append((desc, "段落序号超出范围"))
            continue
        start, end, body = paras[idx]
        current = para_text(body)
        # 有期望文字时必须匹配；空字符串表示该单元格本来就是空的
        if expect and expect not in current:
            fail.append((desc, "占位符不匹配，实际为: %s" % current[:30]))
            continue
        if not expect and current.strip():
            fail.append((desc, "期望为空单元格，实际为: %s" % current[:30]))
            continue
        # 注意：body 不包含 <w:p> 开标签与 </w:p> 闭标签，
        # 因此回写时必须把这两个标签补回去，否则会丢掉整个段落。
        open_tag = re.match(r"<w:p(?:\s[^>]*)?>", xml[start:]).group(0)
        new_body = replace_paragraph_text(body, content)
        xml = xml[:start] + open_tag + new_body + "</w:p>" + xml[end:]
        ok += 1

    after = count_paragraphs(xml)
    print("\n填写成功 %d 处，失败 %d 处" % (ok, len(fail)))
    for desc, why in fail:
        print("   [未填写] %s -> %s" % (desc, why))
    print("段落数：%d -> %d %s" % (before, after, "（一致，结构未破坏）" if before == after else "（不一致，请检查！）"))

    # 3. 写回 docx
    blobs["word/document.xml"] = xml.encode("utf-8")
    tmp = DOCX + ".tmp"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
        for i in items:
            zout.writestr(i, blobs[i.filename])
    os.replace(tmp, DOCX)
    print("已写回:", os.path.basename(DOCX))


if __name__ == "__main__":
    main()
