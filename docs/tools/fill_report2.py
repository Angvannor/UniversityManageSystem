def qn(tag):
    return W + tag


# 标签匹配前先"归一化"：去掉所有全角/半角引号，只比较实质内容。
#
# 【为什么需要它】模板里有些标签带全角引号，例如
#   「4. 与 V1.0 相比，本组对“需求如何形成”的理解发生了什么变化？」
# 如果脚本里把这对引号写成「」或直引号，整串相等就会【静默匹配不上】——
# 段落填不进去，日志里也看不出问题（这个坑真的踩了：
# 反思第 4 问因此没有被填上，靠核对段落填充条数才发现）。
_QUOTE_RE = re.compile(r"[“”「」『』\"']")


def norm_label(s):
    """把标签里的引号统一去掉，避免因引号写法不同而匹配失败。"""
    return _QUOTE_RE.sub("", (s or "").strip())


def para_text(p):
    return "".join(t.text or "" for t in p.iter(qn("t")))


def set_paragraph_text(p, text):
    """把段落的文字整体替换成 text（保留第一个 run 的格式）。

    做法：删掉所有 w:r，再插入一个新 run。这样不会留下旧文字，
    也不会像字符串替换那样产生嵌套的 <w:t>。
    """
    runs = p.findall(qn("r"))
    rpr = None
    for r in runs:
        if rpr is None:
            rpr = r.find(qn("rPr"))
        p.remove(r)

    new_run = ET.SubElement(p, qn("r"))
    if rpr is not None:
        new_run.append(copy.deepcopy(rpr))
    t = ET.SubElement(new_run, qn("t"))
    t.set(XML_SPACE, "preserve")
    t.text = text if text is not None else ""


def set_cell_text(tc, text):
    """设置单元格文字。text 里的 \\n 会拆成多个段落（保留原段落格式）。"""
    lines = str(text).split(SEP) if text else [""]

    paras = tc.findall(qn("p"))
    if not paras:
        # 理论上不会发生，兜底建一个空段落
        paras = [ET.SubElement(tc, qn("p"))]

    template = paras[0]
    for p in paras:
        tc.remove(p)

    for line in lines:
        new_p = copy.deepcopy(template)
        set_paragraph_text(new_p, line)
        tc.append(new_p)


def row_cells(tr):
    return tr.findall(qn("tc"))


def fill_table(tbl, rows, need_rows=None):
    """把 rows 写进表格：表头保留，数据行不够就克隆最后一行。"""
    trs = tbl.findall(qn("tr"))
    if not trs:
        return
    header = trs[0]
    data_trs = trs[1:]

    need = need_rows if need_rows is not None else len(rows)
    # 补足行数（克隆最后一行，保留其单元格格式）
    while len(data_trs) < need:
        clone = copy.deepcopy(data_trs[-1] if data_trs else header)
        tbl.append(clone)          # 追加到表格末尾
        data_trs.append(clone)

    for i in range(need):
        cells = row_cells(data_trs[i])
        row = rows[i] if i < len(rows) else [""] * len(cells)
        for j, tc in enumerate(cells):
            set_cell_text(tc, row[j] if j < len(row) else "")

    # 多余的行删掉（表格留空行不好看）
    for tr in data_trs[need:]:
        tbl.remove(tr)


def find_tables(body):
    """按表头文字给表格起名，返回 {名称: 元素}；同名的按出现顺序存成列表。"""
    found = {}
    for tbl in body.iter(qn("tbl")):
        trs = tbl.findall(qn("tr"))
        if not trs:
            continue
        header = "|".join(
            "".join(para_text(p) for p in tc.findall(qn("p"))).strip()
            for tc in row_cells(trs[0])
        )
        found.setdefault(header, []).append(tbl)
    return found


